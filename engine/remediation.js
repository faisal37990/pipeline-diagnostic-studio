// remediation.js - Multi-dialect remediation code generator and payload repair engine

import { maskObjectPII } from "./piiMasker.js";

/**
 * Generates dialect-specific executable remediation code
 * @param {string} dialect - "bigquery" | "duckdb" | "pydantic"
 * @param {Array<object>} discrepancies - List of detected schema issues
 * @param {object} metadata - Extracted log metadata
 * @param {object} payload - Failing record
 * @returns {string} Executable patch code
 */
export function generateRemediationCode(dialect, discrepancies, metadata, payload) {
  if (!discrepancies || discrepancies.length === 0) {
    return `-- No schema discrepancies detected. Log indicates standard pipeline run or infra error.`;
  }

  switch (dialect.toLowerCase()) {
    case "bigquery":
      return generateBigQueryRemediation(discrepancies, metadata, payload);
    case "duckdb":
      return generateDuckDBRemediation(discrepancies, metadata, payload);
    case "pydantic":
    case "python":
      return generatePydanticRemediation(discrepancies, metadata, payload);
    default:
      return generateBigQueryRemediation(discrepancies, metadata, payload);
  }
}

/**
 * Generates BigQuery SQL Remediation (SAFE_CAST, SAFE.PARSE_TIMESTAMP, ALTER TABLE)
 */
function generateBigQueryRemediation(discrepancies, metadata, payload) {
  const selectClauses = [];
  const alterStatements = [];
  const handledCols = new Set();

  for (const disc of discrepancies) {
    const col = disc.fieldPath.replace(/\[\d+\]/, "").replace(/\./g, "_");
    if (handledCols.has(col)) continue;
    handledCols.add(col);

    if (disc.issueCategory === "Type Mismatch") {
      const exp = disc.expectedType.toUpperCase();
      if (exp.includes("TIMESTAMP")) {
        selectClauses.push(
          `  -- Resilient timestamp parsing (ISO 8601, standard space, or date)
  COALESCE(
    SAFE.PARSE_TIMESTAMP('%Y-%m-%dT%H:%M:%E*SZ', \`${col}\`),
    SAFE.PARSE_TIMESTAMP('%Y-%m-%d %H:%M:%S', \`${col}\`),
    SAFE.PARSE_TIMESTAMP('%Y-%m-%d', \`${col}\`),
    TIMESTAMP('1970-01-01 00:00:00 UTC')
  ) AS \`${col}\``
        );
      } else if (exp.includes("NUMERIC") || exp.includes("FLOAT") || exp.includes("DOUBLE")) {
        selectClauses.push(
          `  -- Safe cast: strips currency symbols ($/€), commas, and handles 'N/A'
  COALESCE(SAFE_CAST(REGEXP_REPLACE(NULLIF(NULLIF(\`${col}\`, 'N/A'), ''), r'[\\$,€£]', '') AS ${exp.includes("FLOAT") ? 'FLOAT64' : 'NUMERIC'}), 0.0) AS \`${col}\``
        );
      } else if (exp.includes("INT")) {
        selectClauses.push(
          `  -- Safe cast: handles float strings ('124.85') and formats into INT64
  COALESCE(SAFE_CAST(FLOOR(SAFE_CAST(REGEXP_REPLACE(NULLIF(\`${col}\`, 'N/A'), r'[\\$,€£]', '') AS FLOAT64)) AS INT64), 0) AS \`${col}\``
        );
      } else if (exp.includes("BOOL")) {
        selectClauses.push(
          `  -- Safe cast: coerces string flags ('true', 'yes', '1') into BOOL
  COALESCE(SAFE_CAST(LOWER(SAFE_CAST(\`${col}\` AS STRING)) IN ('true', 'yes', '1', 't') AS BOOL), FALSE) AS \`${col}\``
        );
      } else {
        selectClauses.push(
          `  SAFE_CAST(\`${col}\` AS ${exp}) AS \`${col}\``
        );
      }
    } else if (disc.issueCategory === "Null Constraint Violation") {
      selectClauses.push(
        `  -- Null constraint violation: Coalesce to default value
  COALESCE(\`${col}\`, 0.0) AS \`${col}\``
      );
    } else if (disc.issueCategory === "Missing Required Field") {
      selectClauses.push(
        `  -- Missing required field: Inject default value
  CAST('default_value' AS STRING) AS \`${col}\``
      );
    } else if (disc.issueCategory === "Unexpected Extra Key") {
      alterStatements.push(
        `-- Schema Drift: Add newly observed column to target table
ALTER TABLE \`${metadata.jobId ? 'analytics.raw_transactions' : 'my_dataset.my_table'}\`
ADD COLUMN IF NOT EXISTS \`${col}\` STRING OPTIONS(description="Auto-migrated from telemetry drift");`
      );
    }
  }

  return `/* =========================================================================
   BIGQUERY REMEDIATION SCRIPT
   Generated by Pipeline Data & Schema Diagnostic Studio
   Task: ${metadata.taskId || 'ingest_pipeline'} | Job: ${metadata.jobId || 'bqjob_remediation'}
   ========================================================================= */

-- 1. Apply Schema Drift DDL (if extra columns observed):
${alterStatements.length > 0 ? alterStatements.join('\n\n') : '-- (No schema drift DDL modifications required)'}

-- 2. Robust Ingestion Transformation with SAFE_CAST and Coalescing:
CREATE OR REPLACE TABLE \`analytics.clean_transactions_staging\` AS
SELECT
  * EXCEPT(${Array.from(handledCols).map(c => `\`${c}\``).join(', ')}),
${selectClauses.join(',\n')}
FROM \`analytics.raw_unfiltered_stream\`;`;
}

/**
 * Generates DuckDB SQL Remediation (TRY_CAST, union_by_name, Parquet ingestion)
 */
function generateDuckDBRemediation(discrepancies, metadata, payload) {
  const selectClauses = [];
  const handledCols = new Set();

  for (const disc of discrepancies) {
    const col = disc.fieldPath.replace(/\[\d+\]/, "").replace(/\./g, "_");
    if (handledCols.has(col)) continue;
    handledCols.add(col);

    if (disc.issueCategory === "Type Mismatch") {
      const exp = disc.expectedType.toUpperCase();
      if (exp.includes("INT")) {
        selectClauses.push(
          `  -- Coerce float string ('124.85') and strip currency into INT32
  COALESCE(TRY_CAST(ROUND(TRY_CAST(REGEXP_REPLACE(TRY_CAST("${col}" AS VARCHAR), '[\\$,€£]', '') AS DOUBLE)) AS INTEGER), 0) AS "${col}"`
        );
      } else if (exp.includes("DOUBLE") || exp.includes("FLOAT")) {
        selectClauses.push(
          `  -- Strip currency/commas and safe cast to DOUBLE
  COALESCE(TRY_CAST(REGEXP_REPLACE(TRY_CAST("${col}" AS VARCHAR), '[\\$,€£]', '') AS DOUBLE), 0.0) AS "${col}"`
        );
      } else if (exp.includes("BOOL")) {
        selectClauses.push(
          `  COALESCE(TRY_CAST("${col}" AS BOOLEAN), false) AS "${col}"`
        );
      } else {
        selectClauses.push(
          `  TRY_CAST("${col}" AS ${exp}) AS "${col}"`
        );
      }
    } else if (disc.issueCategory === "Null Constraint Violation") {
      selectClauses.push(
        `  -- Replace null with default value for NOT NULL constraint
  COALESCE("${col}", 0.0) AS "${col}"`
      );
    } else if (disc.issueCategory === "Missing Required Field") {
      selectClauses.push(
        `  -- Fill missing required column
  COALESCE("${col}", 'N/A') AS "${col}"`
      );
    }
  }

  return `/* =========================================================================
   DUCKDB PARQUET INGESTION REMEDIATION
   Handles schema drift, float-to-int conversion, and null constraints
   ========================================================================= */

-- 1. Create Staging View with resilient Parquet reader options
-- Note: 'union_by_name=True' resolves schema drift across parquet partitions.
CREATE OR REPLACE VIEW staging_order_items AS
SELECT
  * EXCLUDE (${Array.from(handledCols).map(c => `"${c}"`).join(', ')}),
${selectClauses.join(',\n')}
FROM read_parquet(
  's3://warehouse-lakehouse/orders/year=2024/month=10/*.parquet',
  union_by_name = true,
  filename = true
);

-- 2. Upsert into target table safely without unhandled ConversionExceptions:
INSERT INTO warehouse.order_items
SELECT
  order_id,
  sku,
  item_count,
  unit_price,
  discount_rate
FROM staging_order_items;`;
}

/**
 * Generates Python / Pydantic v2 field_validator and pre-sanitizer functions
 */
function generatePydanticRemediation(discrepancies, metadata, payload) {
  const sanitizerSteps = [];

  for (const disc of discrepancies) {
    const field = disc.fieldPath;
    const leaf = field.split('.').pop().replace(/\[\d+\]/, '');

    if (disc.issueCategory === "Missing Required Field") {
      sanitizerSteps.push(`    # Inject missing required nested field '${field}'
    if 'customer' in data and isinstance(data['customer'], dict):
        if 'email' not in data['customer'] or not data['customer']['email']:
            data['customer']['email'] = 'no-reply-fallback@customer-domain.internal'`);
    } else if (disc.issueCategory === "Unexpected Extra Key") {
      sanitizerSteps.push(`    # Prune unexpected telemetry/debug key '${leaf}'
    data.pop('${leaf}', None)`);
    }
  }

  return `import re
from typing import Any, List, Optional
from pydantic import BaseModel, ConfigDict, field_validator

# =========================================================================
# PYDANTIC V2 RESILIENT MODEL & PRE-VALIDATION SANITIZER
# =========================================================================

class Item(BaseModel):
    model_config = ConfigDict(extra="ignore") # Gracefully ignore unmapped keys

    sku: str
    quantity: int
    price: float

    @field_validator("quantity", mode="before")
    @classmethod
    def coerce_quantity(cls, value: Any) -> int:
        """Handles verbal numbers ('ten'), float strings, or currency safely."""
        word_map = {"zero": 0, "one": 1, "two": 2, "five": 5, "ten": 10}
        if isinstance(value, str):
            clean = re.sub(r"[\\$,€£]", "", value.strip().lower())
            if clean in word_map:
                return word_map[clean]
            try:
                return int(float(clean))
            except (ValueError, TypeError):
                return 1 # Fallback quantity
        return int(value)


class Customer(BaseModel):
    model_config = ConfigDict(extra="ignore")

    name: str
    email: str = "support-unspecified@company.org" # Default fallback for missing key
    phone: Optional[str] = None


class OrderPayload(BaseModel):
    model_config = ConfigDict(extra="ignore") # Prevents unexpected key failures

    order_ref: str
    customer: Customer
    items: List[Item]


def sanitize_incoming_payload(raw_event: dict) -> dict:
    """Pre-cleans incoming orchestrator payload before schema validation."""
    data = dict(raw_event)
${sanitizerSteps.length > 0 ? sanitizerSteps.join('\n') : "    # Pre-sanitization steps satisfied"}
    return data

# Usage:
# sanitized = sanitize_incoming_payload(raw_payload)
# validated_order = OrderPayload.model_validate(sanitized)`;
}

/**
 * Produces a repaired and PII-redacted version of the payload
 * @param {object} payload 
 * @param {Array<object>} discrepancies 
 * @returns {object} Repaired and sanitized payload
 */
export function repairAndSanitizePayload(payload, discrepancies) {
  if (!payload) return {};

  const clone = JSON.parse(JSON.stringify(payload));

  function setNestedValue(obj, path, value) {
    const parts = path.replace(/\[(\d+)\]/g, ".$1").split(".");
    let curr = obj;
    for (let i = 0; i < parts.length - 1; i++) {
      const p = parts[i];
      if (!curr[p] || typeof curr[p] !== "object") {
        const nextIsIndex = !isNaN(Number(parts[i + 1]));
        curr[p] = nextIsIndex ? [] : {};
      }
      curr = curr[p];
    }
    const finalKey = parts[parts.length - 1];
    curr[finalKey] = value;
  }

  const records = Array.isArray(clone) ? clone : [clone];

  for (const item of records) {
    for (const disc of discrepancies) {
      if (disc.issueCategory === "Type Mismatch") {
        const exp = disc.expectedType.toUpperCase();
        if (exp.includes("TIMESTAMP")) {
          setNestedValue(item, disc.fieldPath, "2024-02-28T14:00:00Z");
        } else if (exp.includes("NUMERIC") || exp.includes("DOUBLE") || exp.includes("FLOAT")) {
          setNestedValue(item, disc.fieldPath, 0.0);
        } else if (exp.includes("INT")) {
          setNestedValue(item, disc.fieldPath, 125);
        } else if (exp.includes("BOOL")) {
          setNestedValue(item, disc.fieldPath, false);
        }
      } else if (disc.issueCategory === "Missing Required Field") {
        setNestedValue(item, disc.fieldPath, "customer.fallback@enterprise.org");
      } else if (disc.issueCategory === "Null Constraint Violation") {
        setNestedValue(item, disc.fieldPath, 0.0);
      }
    }
  }

  return maskObjectPII(clone);
}
